"""Derive the video VAE encoder's causal 3-D convolution (implicit GEMM) from the f16-in f16-out WMMA matmul.

The conv is the matmul with exactly one thing substituted: the load that stages
a row of A becomes the im2col gather. Everything else -- W staging, the k-loop,
the LDS budget, the epilogue -- is the matmul's. Doing the substitution here,
by anchored edits that fail loudly if the source moves, means the 64-wide and
32-wide convs cannot drift from their matmuls or from each other.

  kernels/matmul_bias_f16_wmma_af16_cf16.loom  ->  kernels/conv3d_f16_wmma.loom (+ _add: residual epilogue)
The derivation is scrfd-loom's tools/gen_conv.py with the gather extended to (dt, dy, dx) taps: frames padded with
two zero frames in front (causal), spatial reflect padding (symmetric pad 1 at stride 1; the stride-2 downsample's
right-only reflect), time stride 1 or 2, and taps_t = 1 for single frames (only the last temporal tap of the weights).
"""
from __future__ import annotations

